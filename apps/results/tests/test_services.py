class ComputeReportCardSummaryTests(SimpleTestCase):
    def test_empty_marks(self):
        summary = compute_report_card_summary([])
        self.assertEqual(summary.mean_score, 0)
        self.assertEqual(summary.mean_grade, "—")
        self.assertEqual(summary.result_band, 0)
        self.assertEqual(summary.result_label, "Not yet available")

    def test_mean_grade_derived_from_mean_score_not_averaged_letters(self):
        # Two subjects at 79 (B) and 81 (A) -> mean score 80 -> mean GRADE
        # should be A (derived from the 80 mean score), even though neither
        # individual subject averages to exactly that letter by itself.
        marks = [
            ReportCardMark(subject_id=1, subject_name="Math", score=79, grade="B"),
            ReportCardMark(subject_id=2, subject_name="English", score=81, grade="A"),
        ]
        summary = compute_report_card_summary(marks)
        self.assertEqual(summary.mean_score, 80.0)
        self.assertEqual(summary.mean_grade, "A")
        # mean_points uses EACH SUBJECT'S OWN grade points (B=4, A=5) -> 4.5
        self.assertEqual(summary.mean_points, 4.5)
        self.assertEqual(summary.result_band, 1)


class GenerateRoleCommentTests(SimpleTestCase):
    def test_no_marks_short_circuits(self):
        summary = compute_report_card_summary([])
        trend = PerformanceTrend(False, "no-data")
        comment = generate_role_comment("classTeacher", 1, "Patricia", summary, trend, "Term 1", 2025)
        self.assertEqual(comment, "No confirmed results yet this term.")

    def test_deterministic_for_same_inputs(self):
        marks = [ReportCardMark(subject_id=1, subject_name="Math", score=85, grade="A")]
        summary = compute_report_card_summary(marks)
        trend = PerformanceTrend(True, "improved", 80, 85, 5)
        c1 = generate_role_comment("dos", 17, "Patricia", summary, trend, "Term 1", 2025)
        c2 = generate_role_comment("dos", 17, "Patricia", summary, trend, "Term 1", 2025)
        self.assertEqual(c1, c2)
        self.assertIn("Patricia", c1)
        self.assertTrue(c1.endswith("Improving from last term."))

    def test_truncates_to_220_chars(self):
        marks = [ReportCardMark(subject_id=1, subject_name="Math", score=85, grade="A")]
        summary = compute_report_card_summary(marks)
        trend = PerformanceTrend(True, "improved", 80, 85, 5)
        comment = generate_role_comment("hm", 1, "X", summary, trend, "Term 1", 2025)
        self.assertLessEqual(len(comment), 220)
