class WeightedAverageTests(SimpleTestCase):
    def test_basic(self):
        self.assertEqual(weighted_average([{"score": 80, "weight_percent": 60}, {"score": 60, "weight_percent": 40}]), 72.0)

    def test_zero_total_weight(self):
        self.assertEqual(weighted_average([{"score": 80, "weight_percent": 0}]), 0.0)

    def test_empty(self):
        self.assertEqual(weighted_average([]), 0.0)

    def test_single_category(self):
        self.assertEqual(weighted_average([{"score": 91, "weight_percent": 50}]), 91.0)

    def test_rounds_to_one_decimal(self):
        # 0.2*69 + 0.3*72 + 0.5*81 = 75.9 (matches the seeded Patricia Nabatanzi
        # Mathematics Paper 1 example from the frontend seed data).
        entries = [
            {"score": 69, "weight_percent": 20},
            {"score": 72, "weight_percent": 30},
            {"score": 81, "weight_percent": 50},
        ]
        self.assertEqual(weighted_average(entries), 75.9)


class SeedFromBitExactnessTests(SimpleTestCase):
    """
    Expected values generated by running the ACTUAL frontend function under
    Node:

        node -e '
        function seedFrom(studentId, term, year) {
          let h = 0;
          const s = `${studentId}-${term}-${year}`;
          for (let i = 0; i < s.length; i++) h = (h * 31 + s.charCodeAt(i)) | 0;
          return h;
        }
        console.log(seedFrom(1, "Term 1", 2025));
        '

    A naive Python port using unmasked ints would NOT reproduce these —
    JS's `| 0` truncates to a 32-bit SIGNED int with wraparound on every
    iteration, which is why several of these are negative.
    """

    def test_bit_exact_against_js(self):
        cases = [
            (1, "Term 1", 2025, 1906481045),
            (17, "Term 1", 2025, 1143494154),
            (22, "Term 1", 2025, 2104950564),
            (6, "Term 3", 2024, 496724311),
            (100, "Term 2", 2026, 292130293),
            (8, "Term 1", 2025, -147340004),
            (9, "Term 1", 2025, -440743011),
            (10, "Term 1", 2025, -1097652093),
            (11, "Term 1", 2025, -1391055100),
            (12, "Term 1", 2025, -1684458107),
            (13, "Term 1", 2025, -1977861114),
            (20, "Term 1", 2025, -1603210718),
            (21, "Term 1", 2025, -1896613725),
            (30, "Term 1", 2025, -2108769343),
            (38, "Term 1", 2025, -161026103),
            (39, "Term 1", 2025, -454429110),
        ]
        for student_id, term, year, expected in cases:
            with self.subTest(student_id=student_id, term=term, year=year):
                self.assertEqual(seed_from(student_id, term, year), expected)


